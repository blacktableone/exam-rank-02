#include <stdio.h>

void	ft_swap(int *a, int *b)
{
	int	c = *a;
	*a = *b;
	*b = c;
}

int	main(void)
{
	int	a = 1;
	int	b = 2;
	ft_swap(&a, &b);
	printf("a is %i, b is %i",a,b);

	return(0);
}
